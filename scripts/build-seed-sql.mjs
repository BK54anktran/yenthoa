#!/usr/bin/env node
// Write db/seed.sql: the schema plus every post, product, banner and the shop info, as plain SQL for
// any MySQL 8 (mysql CLI, phpMyAdmin, Vibe Host, ...). Safe to import more than once: existing rows are kept.
//   npm run db:sql
import fs from "node:fs";
import path from "node:path";
import mysql from "mysql2";
import { SCHEMA } from "../src/lib/db.ts";
import { DEFAULT_SHOP, DEFAULT_SLIDES } from "../src/lib/defaults.ts";
import { normalizeSpecs, normalizeVariants } from "../src/lib/variants.ts";

const q = (v) => (v === null || v === undefined ? "NULL" : mysql.escape(v));
const json = (v) => mysql.escape(JSON.stringify(v));
const readDir = (dir) => fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort().map((f) => JSON.parse(fs.readFileSync(path.join(dir, f), "utf8")));

const out = [];
out.push(`-- Yen Thoa website: database + schema + sample data (generated by scripts/build-seed-sql.mjs, do not edit by hand)
--
-- This one file is enough to set the database up. Run it from the MySQL shell or the command line:
--     mysql> source db/seed.sql
--     mysql -u root -p < db/seed.sql          (cmd / bash; in PowerShell use: mysql -u root -p -e "source db/seed.sql")
-- It creates the database \`yenthoa_db\` (utf8mb4), the tables and the sample data, then you set
--     DATABASE_URL=mysql://USER:PASSWORD@127.0.0.1:3306/yenthoa_db
-- Importing again is safe: existing rows (same slug / key) are kept, so your edits are never overwritten.
--
-- Importing into a database that already exists under another name (phpMyAdmin, a hosting panel)?
-- Delete the two lines CREATE DATABASE and USE below, select your database, then import.
SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

CREATE DATABASE IF NOT EXISTS \`yenthoa_db\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE \`yenthoa_db\`;
`);
for (const sql of SCHEMA) out.push(`${sql};\n`);

const posts = readDir("src/content/posts");
out.push(`-- ${posts.length} posts`);
for (const p of posts) {
  out.push(`INSERT IGNORE INTO posts (slug, title, date, section, excerpt, img, html, published) VALUES (${[p.slug, p.title, p.date, p.section, p.excerpt, p.img, p.html].map(q).join(", ")}, 1);`);
}
const products = readDir("src/content/products");
out.push(`\n-- ${products.length} products`);
for (const p of products) {
  out.push(
    `INSERT IGNORE INTO products (slug, name, brand, types, price, price_max, img, gallery, colors, variants, specs, short_html, html, active) VALUES (${[
      q(p.slug), q(p.name), q(p.brand), json(p.types), Number(p.price), Number(p.priceMax), q(p.img), json(p.gallery), json(p.colors), json(normalizeVariants(p.variants)), json(normalizeSpecs(p.specs)), q(p.shortHtml), q(p.html),
    ].join(", ")}, 1);`,
  );
  // products imported before colour variants existed get them, existing variants are never replaced
  const vs = normalizeVariants(p.variants);
  if (vs.length) out.push(`UPDATE products SET variants = ${json(vs)} WHERE slug = ${q(p.slug)} AND variants IS NULL;`);
  const sp = normalizeSpecs(p.specs);
  if (sp.length) out.push(`UPDATE products SET specs = ${json(sp)} WHERE slug = ${q(p.slug)} AND specs IS NULL;`);
  // databases imported before the label fix hold a pasted description in one spec label of these two products
  if (["xe-lexi", "jupiter-fi"].includes(p.slug)) out.push(`UPDATE products SET specs = ${json(sp)} WHERE slug = ${q(p.slug)} AND CAST(specs AS CHAR) LIKE '%Giá bán lẻ đề xuất%';`);
}
out.push(`\n-- product codes: SP + number, editable in the admin`);
out.push(`UPDATE products SET code = CONCAT('SP', LPAD(id, 4, '0')) WHERE code IS NULL OR code = '';`);
out.push(`\n-- shop info`);
out.push(`INSERT IGNORE INTO settings (k, v) VALUES ('shop', ${json(DEFAULT_SHOP)});`);
out.push(`\n-- home banners (only when the table is empty)`);
out.push(`SET @no_slides = (SELECT COUNT(*) = 0 FROM hero_slides);`);
DEFAULT_SLIDES.forEach((s, i) => {
  out.push(`INSERT INTO hero_slides (eyebrow, title, sub, img, link, sort, active) SELECT ${[q(s.eyebrow), q(s.title), q(s.sub), q(s.img), q(s.link ?? null), i].join(", ")}, 1 FROM DUAL WHERE @no_slides;`);
});
out.push(`\nSET FOREIGN_KEY_CHECKS = 1;\n`);

fs.mkdirSync("db", { recursive: true });
fs.writeFileSync("db/seed.sql", out.join("\n"));
console.log(`db/seed.sql: ${posts.length} posts, ${products.length} products, ${DEFAULT_SLIDES.length} banners, ${(fs.statSync("db/seed.sql").size / 1e6).toFixed(2)} MB`);
